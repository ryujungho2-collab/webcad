import { createRoot } from "react-dom/client";
import * as THREE from "three";
import { App } from "../src/App";
import "../src/styles.css"; import "../src/ui/tokens.css"; import "../src/ui/workstation.css"; import "../src/ui/commands.css"; import "../src/ui/menu.css"; import "../src/ui/explorer.css"; import "../src/ui/inspector.css";
import { cadDocument } from "../src/state/cadDocument";
import { cadHistory } from "../src/state/history";
import { dispatchCadCommand } from "../src/state/dispatchCadCommand";
import { saveDocumentToCache, openDocumentFile } from "../src/state/documentFile";
import { serializeDocument } from "@agent-webcad/cad-document";
import { isDocumentCommandPending } from "../src/state/documentCommandQueue";
import { resetTestDocument } from "./helpers/documentHarness";
import { installBrowserChecks } from "./helpers/browserChecks";
import { click, physical, choose, text, input, waitFor, pause, find } from "./helpers/physicalInput";

resetTestDocument();
await dispatchCadCommand({ type: "create-primitive", id: "body", primitive: "box", params: { width: 30, depth: 20, height: 10 }, position: [15, 5, 0] });
saveDocumentToCache();
let camera: THREE.Camera;
const update = THREE.Camera.prototype.updateMatrixWorld;
THREE.Camera.prototype.updateMatrixWorld = function(force) { camera = this; return update.call(this, force); };
createRoot(document.getElementById("root")!).render(<App />);
const panel = () => document.querySelector<HTMLDialogElement>('.model-views-dialog[open]');
async function panelClick(name: string) { const button = [...panel()!.querySelectorAll("button")].find(b => b.textContent === name); if (!button || button.disabled) throw new Error("Missing or disabled panel action: " + name); await physical(button); }
const views = () => Object.values(cadDocument.modelViews ?? {});
const h = () => cadHistory.getPastLabels().length;
const geometry = () => { const { revision: _, modelViews: __, ...model } = cadDocument; return JSON.stringify(model); };
const sample = () => [new THREE.Vector3(0, 0, 0), new THREE.Vector3(25, 10, 10), new THREE.Vector3(-10, 12, 4)].map(p => p.project(camera).toArray());
const close = async () => { await click("Close model views"); await waitFor(() => !panel()); };
const open = async () => { await physical(document.getElementById("tools-tab-view")!); await click("Model views"); await waitFor(() => !!panel()); };
const settled = async () => { await waitFor(() => !isDocumentCommandPending()); await new Promise(resolve => setTimeout(resolve, 600)); };
const button = document.getElementById("run-model-views") as HTMLButtonElement, output = document.getElementById("model-views-result")!;
button.onclick = async () => {
  button.disabled = true; const lines: string[] = [], check = (value: unknown, label: string) => { if (!value) throw new Error(label); lines.push(`PASS: ${label}`); };
  try {
    await waitFor(() => !!document.querySelector("#root canvas") && !!camera); await settled();
    const model = geometry(); await open(); const initialHistory = h();
    check(h() === initialHistory && geometry() === model, "Opening model views leaves geometry and History unchanged");
    await text("Model view name", "Perspective detail"); await click("Save current view"); await settled();
    check(views().length === 1 && views()[0].camera.projection === "perspective", "Ribbon saves the actual perspective camera");
    check(h() === initialHistory + 1 && geometry() === model, "Saving creates one History entry without changing the model");
    const perspectiveId = views()[0].id, perspectiveName = views()[0].name;
    await click("Top view"); await settled();
    check(camera instanceof THREE.OrthographicCamera, "Top view switches to orthographic projection");
    await panelClick("Fit all geometry"); await settled(); const topSample = sample();
    await text("Model view name", "Top drawing"); await click("Save current view"); await settled();
    check(views().length === 2 && views().some(v => v.name === "Top drawing" && v.camera.projection === "orthographic"), "Top framing saves as a second independent view");
    const topId = views().find(v => v.name === "Top drawing")!.id;
    await click("Front view"); await settled();
    check(sample().some((p, i) => Math.abs(p[1] - topSample[i][1]) > 0.01), "Front view changes the viewing direction");
    const beforeRecall = h(); await click("Recall view"); await settled();
    check(sample().every((p, i) => p.every((n, axis) => Math.abs(n - topSample[i][axis]) < 1e-6)), "Recall restores saved zoom, direction, target and framing after rendered frames");
    check(h() === beforeRecall && geometry() === model, "Recall changes neither History nor model geometry");
    await click("Right view"); await settled();
    check(camera.getWorldDirection(new THREE.Vector3()).distanceTo(new THREE.Vector3(-1, 0, 0)) < 1e-6, "Right view uses the model X direction without rotating geometry");
    await click("Isometric view"); await settled();
    check(camera.getWorldDirection(new THREE.Vector3()).distanceTo(new THREE.Vector3(-1, 1, -1).normalize()) < 1e-6, "Isometric view remains available with the chosen projection");
    await click("Recall view"); await settled();
    await text("Model view name", "Roof plan"); await click("Rename view"); await settled();
    check(cadDocument.modelViews![topId].name === "Roof plan", "Rename preserves the saved view identity");
    await text("Model view name", perspectiveName); const beforeDuplicate = h(); await click("Rename view"); await settled();
    check(!!panel()?.querySelector('[role="alert"]') && h() === beforeDuplicate && cadDocument.modelViews![topId].name === "Roof plan", "Duplicate names preserve saved data, draft input and History with an error");
    await text("Model view name", "Roof plan"); await close(); await click("Undo"); await settled();
    check(cadDocument.modelViews![topId].name === "Top drawing", "Undo reverses view rename");
    await click("Redo"); await settled(); check(cadDocument.modelViews![topId].name === "Roof plan", "Redo restores view rename");
    await click("2D"); await settled();
    await input({ type: "key", key: "k", modifiers: 2 }); await input({ type: "text", text: "Recall view Roof plan" }); await pause();
    const command = document.getElementById(`palette-recall-model-view-${topId}`); check(!!command, "Ctrl+K discovers named saved views");
    await physical(command!); await settled();
    check(document.querySelector('.viewport-label')?.textContent?.includes("Orthographic") && sample().every((p, i) => p.every((n, axis) => Math.abs(n - topSample[i][axis]) < 1e-6)), "Palette recall from 2D restores the saved 3D camera without a transition overwrite");
    await open(); await choose("Saved model view", 1); await click("Recall view"); await settled();
    check(camera instanceof THREE.PerspectiveCamera && cadDocument.modelViews![perspectiveId].name === perspectiveName, "Recall switches back to the saved perspective camera");
    await panelClick("Fit all geometry"); await settled(); const fitted = sample(); await click("Update view from camera"); await settled();
    check(cadDocument.modelViews![perspectiveId].camera.projection === "perspective", "Update replaces framing while preserving view identity and projection");
    const portable = serializeDocument(cadDocument); await close();
    await openDocumentFile(new File([portable], "views.webcad")); await settled(); await open();
    check(views().length === 2, "Portable file reopen preserves both named views");
    await choose("Saved model view", 1); await click("Recall view"); await settled();
    check(sample().every((p, i) => p.every((n, axis) => Math.abs(n - fitted[i][axis]) < 1e-6)), "Reopened view restores the updated perspective framing");
    const beforeDelete = h(); await click("Delete view"); await settled();
    check(views().length === 1 && h() === beforeDelete + 1, "Delete removes exactly one selected saved view");
    await close(); await click("Undo"); await settled(); check(views().length === 2, "Undo restores a deleted view");
    await input({ type: "key", key: "k", modifiers: 2 }); await input({ type: "text", text: "Model views" }); await pause();
    await physical(document.getElementById("palette-model-views")!); await waitFor(() => !!panel());
    check(true, "Ctrl+K also opens saved-view management"); await close();
    check(geometry() === model, "Save, rename, recall, Fit, update, delete and file reload preserve every modeling field");
    output.textContent = lines.join("\n") + `\nALL ${lines.length} CHECKS PASSED`;
  } catch (error) { output.textContent = lines.join("\n") + `\nFAIL: ${error instanceof Error ? error.message : String(error)}`; }
  finally { button.disabled = false; }
};
installBrowserChecks(button, output);
