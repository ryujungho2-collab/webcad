import assert from "node:assert/strict";
import { beforeEach, test } from "node:test";
import { cadDocument } from "../src/state/cadDocument";
import { dispatchCadCommand } from "../src/state/dispatchCadCommand";
import { planPointTransform } from "../src/state/pointTransformCommands";
import { parsePointEntry, applyPolarLocks } from "../src/precision/pointInput";
import { WORK_PLANES, planeToWorld, worldToPlane } from "../src/precision/workPlane";
import { getWorldDrawingGeometry } from "../src/precision/worldGeometry";
import { cadHistory, undoDocument, redoDocument } from "../src/state/history";
import { documentState, resetTestDocument } from "./helpers/documentHarness";
beforeEach(resetTestDocument);
test("absolute/relative coordinate and polar locks preserve unit and base semantics", () => {
  assert.deepEqual(parsePointEntry("2m,1m"), [2000, 1000]);
  assert.deepEqual(parsePointEntry("#2cm,30", [100, 50]), [20, 30]);
  assert.deepEqual(parsePointEntry("@2cm,-10", [100, 50]), [120, 40]);
  assert.equal(parsePointEntry("@1,2"), null); assert.equal(parsePointEntry("bad", [0, 0]), null);
  const polar = parsePointEntry("@10cm<90deg", [20, 30])!;
  assert.ok(Math.abs(polar[0] - 20) < 1e-8); assert.equal(polar[1], 130);
  const locked = applyPolarLocks([10, 20], [50, 25], { length: 100, angle: 90 });
  assert.ok(Math.abs(locked[0] - 10) < 1e-8); assert.equal(locked[1], 120);
});
for (const plane of ["XY", "XZ", "YZ"] as const) test(`${plane}: explicit base/target moves, copies and rotates a drawing around the chosen centre`, async () => {
  const frame = WORK_PLANES[plane];
  assert.ok((await dispatchCadCommand({ type: "create-drawing", id: "line", drawing: "line", params: { workPlane: plane, points: [[10, 5], [30, 5]].map((point) => planeToWorld(point as [number, number], frame)) } })).ok);
  const get = (id: string) => getWorldDrawingGeometry(cadDocument.objects[id], Object.values(cadDocument.features).find((entry) => entry.output === id)!)!;
  const original = documentState(); cadHistory.clear();
  const rotation = planPointTransform(cadDocument, ["line"], "rotate", planeToWorld([0, 0], frame), planeToWorld([0, 0], frame), 90, plane)!;
  assert.ok((await dispatchCadCommand(rotation)).ok);
  const points = get("line").points!.map((point) => worldToPlane(point, frame));
  assert.ok(Math.abs(points[0][0] + 5) < 1e-6 && Math.abs(points[0][1] - 10) < 1e-6);
  const rotated = documentState(); assert.equal(cadHistory.getPastLabels().length, 1);
  assert.ok(undoDocument()); assert.deepEqual(documentState(), original); assert.ok(redoDocument()); assert.deepEqual(documentState(), rotated);
  const move = planPointTransform(cadDocument, ["line"], "move", planeToWorld([50, 50], frame), planeToWorld([70, 80], frame), 0, plane)!;
  assert.ok((await dispatchCadCommand(move)).ok);
  const after = get("line").points!.map((point) => worldToPlane(point, frame));
  assert.ok(Math.abs(after[0][0] - 15) < 1e-6 && Math.abs(after[0][1] - 40) < 1e-6);
  const copy = await dispatchCadCommand(planPointTransform(cadDocument, ["line"], "copy", planeToWorld([0, 0], frame), planeToWorld([100, 0], frame), 0, plane)!);
  assert.ok(copy.ok); const copied = worldToPlane(get(copy.createdIds[0]).points![0], frame); assert.ok(Math.abs(copied[0] - 115) < 1e-6);
  assert.equal(planPointTransform(cadDocument, ["line"], "move", [0, 0, 0], [0, 0, 0], 0, plane), null);
});
test("point copy in a sketch retains internal relations, while conflicts and locked sources remain atomic", async () => {
  await dispatchCadCommand({ type: "create-sketch", id: "sketch", workPlane: "XY" });
  await dispatchCadCommand({ type: "add-sketch-geometry", sketchId: "sketch", geometry: { id: "line", kind: "line", startId: "a", endId: "b", segmentId: "edge", start: [0, 0], end: [100, 0] } });
  await dispatchCadCommand({ type: "add-sketch-constraint", sketchId: "sketch", constraint: { id: "fixed", kind: "fixed-point", point: { geometryId: "line", pointId: "a" }, value: [0, 0] } });
  const before = documentState(), history = cadHistory.getPastLabels().length;
  const rejected = await dispatchCadCommand(planPointTransform(cadDocument, ["line"], "move", [0, 0, 0], [20, 20, 0], 0, "XY", "sketch")!);
  assert.equal(rejected.ok, false); assert.equal(rejected.diagnostic?.kind, "sketch-conflict"); assert.deepEqual(documentState(), before); assert.equal(cadHistory.getPastLabels().length, history);
  const copy = await dispatchCadCommand(planPointTransform(cadDocument, ["line"], "copy", [0, 0, 0], [20, 20, 0], 0, "XY", "sketch")!);
  assert.ok(copy.ok); assert.equal(cadDocument.sketches!.sketch.constraints.length, 2);
  await dispatchCadCommand({ type: "set-layer-locked", layerId: "layer-default", locked: true });
  assert.equal(planPointTransform(cadDocument, ["line"], "copy", [0, 0, 0], [20, 20, 0], 0, "XY", "sketch"), null);
});
