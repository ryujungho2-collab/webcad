type AnyCommand=Parameters<typeof dispatchCadCommand>[0];
const wallDef=(sourceIds:string[],patch:Partial<ArchitectureWall>={}):Extract<AnyCommand,{type:"create-wall"}>["definition"]=>({mode:"centerline",sourceObjectIds:sourceIds,height:2700,thickness:200,baseLevel:0,openings:[],...patch});
