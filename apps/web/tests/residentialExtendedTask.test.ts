  const before=await importExtended(),after=documentState();
  assert.equal(after.rootObjects.filter(id=>cadDocument.objects[id].visible).length,31,"excluded annotation layers import nothing visible");
  assert.ok(undoDocument());assert.deepEqual(documentState(),before);
  assert.ok(redoDocument());assert.deepEqual(documentState(),after);
  assert.equal(layerByName("A-외곽벽"),`dxf-${EXTENDED_TAG}-A-외곽벽`);
  assert.ok(Object.keys(cadDocument.layers).some(id=>cadDocument.layers[id].name==="G-해치"));
  assert.equal(Object.keys(cadDocument.blocks!).length,3,"only the three real symbol definitions arrive");
  assert.ok(cadDocument.blocks![`block-dxf-${EXTENDED_TAG}-1`],"nested 기준-창 definition is retained");
  assert.deepEqual(cadDocument.blocks![`block-dxf-${EXTENDED_TAG}-1`].members.length,2,"기준-창 keeps its nested 기준-심벌 insert plus symbol line");
  assert.ok(feature(refs.windowSymbol).params.blockId,"block symbols define nested references");
  const receipt=feature(refs.wallS).params.floorPlanSource as Record<string,unknown>;
  assert.equal(receipt.unitMm,1);
  assert.deepEqual(receipt.unitCheck,{measuredMm:6000,expectedMm:6000});
