const importOptions=(patch:Partial<Parameters<typeof importExtended>[1]>={}):NonNullable<Parameters<typeof planParsedDxfImport>[3]>=>({layerRoles:{...EXTENDED_ROLES},unitCheck:{measuredMm:6000,expectedMm:6000},sourceName:"Residential extended diagnostics",excludeText:true,usedOnly:false,...patch});
async function importExtended(dxf:string=residentialExtendedDxf(),options=importOptions(),tag=EXTENDED_TAG){
  const task=planParsedDxfImport(parseDxf(dxf),new Map(),tag,options);
  assert.ok(task.ok,task.ok?"":task.reason);
  const before=documentState();await run(task.command);return before;
}
