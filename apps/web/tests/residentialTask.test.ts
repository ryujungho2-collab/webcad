test("Q1 · 진단·정리: PURGE 후보, 중복/T자/끝단 공극 보고, 0.05mm 브리지 면 생성",async()=>{
  await importResidential();
  const unusedId=Object.entries(cadDocument.blocks!).find(([,block])=>block.name==="가구-미지정")![0];
  const candidates=floorPurgeCandidates(cadDocument);
  assert.deepEqual(candidates.blockIds,[unusedId]);
  assert.deepEqual(candidates.layerIds,[]);
  const before=documentState();await run({type:"purge-unused",blockIds:[unusedId],layerIds:[]});
  assert.equal(cadDocument.blocks?.[unusedId],undefined);
  assert.ok(undoDocument()&&redoDocument()&&undoDocument());assert.deepEqual(documentState(),before);
  const zero=analyzeFloorSelection(cadDocument,diagIds(),0,false);
  assert.ok(zero.issues.some(i=>i.kind==="duplicate"&&i.objectIds.sort()[0]===refs.dup1),"duplicate boundary reported");
  assert.ok(zero.issues.some(i=>i.kind==="branch"),"T junction reported");
  assert.equal(zero.issues.filter(i=>i.kind==="nonplanar").length,0);
  assert.equal(zero.issues.filter(i=>i.kind==="gap").length,7);
  assert.ok(zero.issues.some(i=>i.kind==="gap"&&Math.abs((i.distanceMm??-1)-0.1)<1e-6),"0.1mm open endpoint distance is reported");
  assert.equal(zero.loops.length,0);
  const repair=analyzeFloorSelection(cadDocument,diagIds(),1,true);
  assert.equal(repair.bridges.length,1);
  assert.ok(Math.abs((repair.bridges[0][0][0]-repair.bridges[1][0][0])-0.1)<1e-6,"unique paired 0.1mm gap proposes an explicit bridge");
  assert.ok(repair.issues.length>0,"remaining duplicates/branches still block the face");
  assert.throws(()=>planFloorTask(cadDocument,intent(diagIds(),"make-face",1,true,"q1-diag")),/Duplicate|T junction|Open endpoint/);
  assert.throws(()=>analyzeFloorSelection(cadDocument,[],1),/Select visible/);
  const terrace=analyzeFloorSelection(cadDocument,[refs.terrace],0.1,true);
  assert.equal(terrace.issues.length,0,JSON.stringify(terrace.issues));
  assert.equal(terrace.bridges.length,1);
  assert.ok(Math.abs((terrace.bridges[0][0][0]-terrace.bridges[1][0][0])-0.05)<1e-9);
  const face=planFloorTask(cadDocument,intent([refs.terrace],"make-face",0.1,true,"q1-face"));
  assert.equal(face.analysis?.issues.length,0);
  assert.equal(face.analysis?.loops.length,1);
  assert.ok(face.summary.some(s=>s.includes("1 regions, 0 holes")));
  await run(face.command);
  const created=Object.values(cadDocument.features).find(f=>f.params.kind==="face");
  assert.ok(created,"bounded face is applied over the repaired terrace boundary");
  assert.deepEqual(created.inputs,[refs.terrace,"floor-bridge-q1-face-0"]);
  const after=documentState(),state=JSON.stringify(cadDocument);
  assert.ok(deserializeDocument(serializeDocument(cadDocument)));
  assert.equal(JSON.stringify(cadDocument),state);
  assert.ok(undoDocument());assert.deepEqual(documentState(),before);
  assert.ok(redoDocument());assert.deepEqual(documentState(),after);
});
